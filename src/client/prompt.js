/**
 * 从面板发起一次总结:任务文本会被预填进新会话的输入框。
 * 第一行固定写「总结视频:标题/链接」,方便会话列表里一眼认出来。
 */
export function buildPrompt(url) {
  return [
    `总结这个视频:${url}`,
    '',
    '流程:',
    '1. 调用 video_summary({ url }) 拿转录稿(工具会自己下载音频/抓字幕并转录,可能要等一两分钟);',
    '2. 读完整份文稿,写一份中文总结:开头 2~4 句结论,然后按时间轴分段,最后列 3~6 条要点;',
    '3. 调用 video_summary_save({ id, summary, takeaways }) 把总结存进「视频总结」面板。',
  ].join('\n')
}
